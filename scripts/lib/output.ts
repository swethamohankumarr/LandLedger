/**
 * Writes the deployed contract address + ABI into the frontend so the dApp can
 * bind to it with no manual copy/paste. Produces a typed TS module and a JSON
 * artifact.
 */
import * as fs from "fs";
import * as path from "path";

const CONTRACTS_DIR = path.join(__dirname, "..", "..", "frontend", "src", "contracts");

export function writeFrontendContract(opts: {
  address: string;
  chainId: number;
  network: string;
  abi: unknown[];
}): void {
  fs.mkdirSync(CONTRACTS_DIR, { recursive: true });

  const deployment = {
    address: opts.address,
    chainId: opts.chainId,
    network: opts.network,
    deployedAt: new Date().toISOString(),
    abi: opts.abi,
  };
  fs.writeFileSync(
    path.join(CONTRACTS_DIR, "deployment.json"),
    JSON.stringify(deployment, null, 2)
  );

  const ts = `// AUTO-GENERATED by scripts (deploy/seed). Do not edit by hand.
// Network: ${opts.network} (chainId ${opts.chainId})
import deployment from "./deployment.json";

export const LAND_REGISTRY_ADDRESS = ${JSON.stringify(opts.address)} as const;
export const LAND_REGISTRY_CHAIN_ID = ${opts.chainId};
export const LAND_REGISTRY_NETWORK = ${JSON.stringify(opts.network)} as const;
export const LAND_REGISTRY_ABI = deployment.abi;
`;
  fs.writeFileSync(path.join(CONTRACTS_DIR, "landRegistry.ts"), ts);
}
